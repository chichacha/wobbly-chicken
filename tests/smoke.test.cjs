const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {parseCSV, buildGroups, available, jaDate, currentEdition} = require('../js/site.js');
const root = path.resolve(__dirname,'..');
const read = file => parseCSV(fs.readFileSync(path.join(root,'data',file),'utf8'));
const editions = read('editions.csv');
const items = read('menu.csv');
const current = currentEdition(editions);
const groups = buildGroups(items.filter(item => item.edition_id === current.edition_id));
assert.equal(current.date,'2026-11-07');
assert.equal(groups.length,4);
assert.equal(groups.reduce((n,g)=>n+g.items.length,0),17);
assert.deepEqual(groups.map(g=>g.title),['お通し','お野菜','お肉＆お魚','ドリンク']);
assert.equal(editions.filter(e=>e.status==='archived').length,2);
assert.ok(buildGroups(items.filter(i=>i.edition_id==='atsuko-20261010')).some(g=>g.title==='麺'));
assert.equal(available('売り切れ'),false);
assert.equal(available('yes'),true);
assert.equal(parseCSV('dish,note\n"A,B","said ""cheers"""\n')[0].note,'said "cheers"');
assert.match(jaDate('2026-11-07'),/11月7日/);
console.log('✅ PASS: 17 current menu items, 4 dynamic categories, 2 archive dates, CSV quotations, statuses & availability');

const script = fs.readFileSync(path.join(root,'js','site.js'),'utf8');
const printView = fs.readFileSync(path.join(root,'print.qmd'),'utf8');
const quarto = fs.readFileSync(path.join(root,'_quarto.yml'),'utf8');
assert.match(printView,/data-page="print"/);
assert.match(script,/params.get\('edition'\)/);
assert.match(script,/window.print\(\)/);
assert.match(script,/filter\(item => item.available\)/);
assert.doesNotMatch(quarto,/page-footer:\s*false/);
console.log('✅ PASS: A4 print page, edition selection, no unavailable dishes, corrected Quarto config');
